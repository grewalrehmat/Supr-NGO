    void updateEventProgress(long eventId, long progress, String status) throws IOException {
        Event event = requireEvent(eventId);
        if (event.goalTarget() == 0 && progress != 0) throw new Problem(409, "This event has no measurable goal.");
        if (!List.of("PLANNED", "ONGOING", "COMPLETED").contains(status)) throw new Problem(400, "Select a valid event status.");
        write(connection -> {
            try (PreparedStatement statement = connection.prepareStatement("UPDATE events SET progress=?,status=? WHERE id=?")) {
                statement.setLong(1, progress); statement.setString(2, status); statement.setLong(3, eventId);
                if (statement.executeUpdate() == 0) throw new Problem(404, "This event does not exist.");
            }
            return null;
        });
    }

    void assignTask(long eventId, String title, String description, String volunteerEmail) throws IOException {
        requireEvent(eventId);
        User volunteer = user(normaliseEmail(volunteerEmail));
        if (volunteer == null || volunteer.role() != Role.VOLUNTEER) throw new Problem(400, "Select a registered volunteer.");
        write(connection -> {
            try (PreparedStatement statement = connection.prepareStatement(
                    "INSERT INTO tasks(event_id,title,description,volunteer_email) VALUES(?,?,?,?)")) {
                statement.setLong(1, eventId); statement.setString(2, title); statement.setString(3, description);
                statement.setString(4, volunteer.email()); statement.executeUpdate();
            }
            return null;
        });
    }

    void recordEventExpense(long eventId, long amount) throws IOException {
        Event event = requireEvent(eventId);
        if (amount < 1 || amount > 999_999_999_999L - event.spent()) throw new Problem(400, "Enter a valid expense amount.");
        write(connection -> {
            try (PreparedStatement statement = connection.prepareStatement("UPDATE events SET spent=spent+? WHERE id=?")) {
                statement.setLong(1, amount); statement.setLong(2, eventId); statement.executeUpdate();
            }
            return null;
        });
    }

    void donate(User donor, String targetType, long targetId, long amount) throws IOException {
        if (donor.role() != Role.INDIVIDUAL && donor.role() != Role.COMPANY) throw new Problem(403, "Only individuals and companies can donate.");
        if (amount < 1 || amount > 999_999_999_999L) throw new Problem(400, "Enter a valid donation amount.");
        if (targetType.equals("PROJECT")) {
            if (!requireProject(targetId).approved()) throw new Problem(409, "Only approved projects can receive donations.");
        } else if (targetType.equals("EVENT")) requireEvent(targetId);
        else throw new Problem(400, "Select a valid donation target.");
        write(connection -> {
            String sql = targetType.equals("PROJECT")
                ? "INSERT INTO donations(target_type,project_id,donor_email,amount,donation_date) VALUES('PROJECT',?,?,?,?)"
                : "INSERT INTO donations(target_type,event_id,donor_email,amount,donation_date) VALUES('EVENT',?,?,?,?)";
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                statement.setLong(1, targetId); statement.setString(2, donor.email());
                statement.setLong(3, amount); statement.setObject(4, LocalDate.now()); statement.executeUpdate();
            }
            return null;
        });
    }

