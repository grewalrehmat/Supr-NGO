    private static void insertProject(Connection connection, Long id, String organisation, String title, String theme,
                                      String district, long budget, String summary, boolean approved, String owner)
            throws SQLException {
        String sql = id == null
            ? "INSERT INTO projects(owner_email,organisation,title,theme,district,budget,summary,approved) VALUES(?,?,?,?,?,?,?,?)"
            : "INSERT INTO projects(id,owner_email,organisation,title,theme,district,budget,summary,approved) VALUES(?,?,?,?,?,?,?,?,?)";
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            int i = 1;
            if (id != null) statement.setLong(i++, id);
            if (owner == null || owner.isBlank()) statement.setNull(i++, java.sql.Types.VARCHAR);
            else statement.setString(i++, owner);
            statement.setString(i++, organisation);
            statement.setString(i++, title);
            statement.setString(i++, theme);
            statement.setString(i++, district);
            statement.setLong(i++, budget);
            statement.setString(i++, summary);
            statement.setBoolean(i, approved);
            statement.executeUpdate();
        }
    }

    private static void setProperty(PreparedStatement statement, int index, Properties properties, String key)
            throws SQLException {
        statement.setString(index, properties.getProperty(key, ""));
    }

    private <T> T read(SqlWork<T> work) {
        try (Connection connection = connect()) { return work.run(connection); }
        catch (SQLException e) { throw new Problem(503, "PostgreSQL is unavailable. Check that the database is running."); }
    }

    private <T> T write(SqlWork<T> work) throws IOException {
        try (Connection connection = connect()) {
            connection.setAutoCommit(false);
            try {
                T result = work.run(connection);
                connection.commit();
                return result;
            } catch (SQLException | RuntimeException e) {
                try { connection.rollback(); } catch (SQLException ignored) {}
                throw e;
            }
        } catch (SQLException e) {
            throw new IOException("Could not save changes to PostgreSQL.", e);
        }
    }

    void bootstrapReviewer(String email, String password) throws IOException {
        if (email == null && password == null) return;
        if (email == null || password == null) throw new IllegalArgumentException("Set both reviewer environment variables.");
        User existing = user(normaliseEmail(email));
        if (existing != null) {
            if (existing.role() != Role.REVIEWER) throw new IllegalArgumentException("Reviewer email already belongs to another role.");
            return;
        }
        register("PACT Reviewer", "PACT", "", "", email, password, Role.REVIEWER);
    }

    User register(String name, String organisation, String registration, String phone,
                  String email, String password, Role role) throws IOException {
        String normalizedEmail = normaliseEmail(email);
        if (normalizedEmail.length() > 254 || !normalizedEmail.matches("[^@\\s]+@[^@\\s]+\\.[^@\\s]+")) throw new Problem(400, "Enter a valid email address.");
        if (password.length() < 8 || password.length() > 128) throw new Problem(400, "Use a password between 8 and 128 characters.");
        if (user(normalizedEmail) != null) throw new Problem(409, "An account already uses that email.");
        byte[] salt = new byte[16];
        RANDOM.nextBytes(salt);
        String saltText = Base64.getEncoder().encodeToString(salt);
        String hashText = Base64.getEncoder().encodeToString(hash(password, salt));
        try {
            write(connection -> {
                try (PreparedStatement statement = connection.prepareStatement(
                        "INSERT INTO users(email,name,organisation,registration,phone,role,salt,password_hash) VALUES(?,?,?,?,?,?,?,?)")) {
                    statement.setString(1, normalizedEmail);
                    statement.setString(2, name);
                    statement.setString(3, organisation);
                    statement.setString(4, registration);
                    statement.setString(5, phone);
                    statement.setString(6, role.name());
                    statement.setString(7, saltText);
                    statement.setString(8, hashText);
                    statement.executeUpdate();
                }
                return null;
            });
        } catch (IOException e) {
            if (e.getCause() instanceof SQLException sql && "23505".equals(sql.getSQLState())) {
                throw new Problem(409, "An account already uses that email.");
            }
            throw e;
        }
        return new User(normalizedEmail, name, organisation, role);
    }

    User user(String email) {
        String normalized = normaliseEmail(email);
        return read(connection -> findUser(connection, normalized));
    }

    private static User findUser(Connection connection, String email) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("SELECT name,organisation,role FROM users WHERE email=?")) {
            statement.setString(1, email);
            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) return null;
                return new User(email, result.getString(1), result.getString(2), Role.valueOf(result.getString(3)));
            }
        }
    }

    User authenticate(String email, String password) {
        String normalized = normaliseEmail(email);
        if (password.length() > 128) return null;
        return read(connection -> {
            try (PreparedStatement statement = connection.prepareStatement("SELECT name,organisation,role,salt,password_hash FROM users WHERE email=?")) {
                statement.setString(1, normalized);
                try (ResultSet result = statement.executeQuery()) {
                    if (!result.next()) { hash(password, new byte[16]); return null; }
                    byte[] salt = Base64.getDecoder().decode(result.getString("salt"));
                    byte[] expected = Base64.getDecoder().decode(result.getString("password_hash"));
                    if (!MessageDigest.isEqual(expected, hash(password, salt))) return null;
                    return new User(normalized, result.getString("name"), result.getString("organisation"), Role.valueOf(result.getString("role")));
                }
            }
        });
    }

    private static String normaliseEmail(String email) { return email.strip().toLowerCase(Locale.ROOT); }

    private static byte[] hash(String password, byte[] salt) {
        PBEKeySpec spec = new PBEKeySpec(password.toCharArray(), salt, 600_000, 256);
        try { return SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256").generateSecret(spec).getEncoded(); }
        catch (GeneralSecurityException e) { throw new IllegalStateException("Password hashing unavailable", e); }
        finally { spec.clearPassword(); }
    }

