    Store(String jdbcUrl, String dbUser, String dbPassword, Path legacyFile) throws IOException {
        this.jdbcUrl = jdbcUrl;
        this.dbUser = dbUser;
        this.dbPassword = dbPassword;
        initialize(legacyFile);
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(jdbcUrl, dbUser, dbPassword);
    }

    private void initialize(Path legacyFile) throws IOException {
        try (Connection connection = connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS users ("
                + "email VARCHAR(254) PRIMARY KEY, name VARCHAR(100) NOT NULL, organisation VARCHAR(150) NOT NULL,"
                + "registration VARCHAR(80) NOT NULL, phone VARCHAR(30) NOT NULL, role VARCHAR(24) NOT NULL,"
                + "salt TEXT NOT NULL, password_hash TEXT NOT NULL)");
            statement.execute("CREATE TABLE IF NOT EXISTS projects ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_email VARCHAR(254) REFERENCES users(email) ON DELETE SET NULL,"
                + "organisation VARCHAR(150) NOT NULL, title VARCHAR(120) NOT NULL, theme VARCHAR(80) NOT NULL,"
                + "district VARCHAR(80) NOT NULL, budget BIGINT NOT NULL CHECK (budget >= 0), summary VARCHAR(1000) NOT NULL, approved BOOLEAN NOT NULL)");
            statement.execute("CREATE TABLE IF NOT EXISTS project_milestones ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,"
                + "milestone_date DATE NOT NULL, title VARCHAR(120) NOT NULL, evidence VARCHAR(1000) NOT NULL)");
            statement.execute("CREATE TABLE IF NOT EXISTS events ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(120) NOT NULL, event_type VARCHAR(40) NOT NULL,"
                + "location VARCHAR(120) NOT NULL, event_date DATE NOT NULL, budget BIGINT NOT NULL CHECK (budget >= 0),"
                + "spent BIGINT NOT NULL DEFAULT 0 CHECK (spent >= 0), description VARCHAR(1000) NOT NULL,"
                + "goal_metric VARCHAR(80) NOT NULL DEFAULT '', goal_target BIGINT NOT NULL DEFAULT 0 CHECK (goal_target >= 0),"
                + "progress BIGINT NOT NULL DEFAULT 0 CHECK (progress >= 0), status VARCHAR(12) NOT NULL DEFAULT 'PLANNED'"
                + " CHECK (status IN ('PLANNED','ONGOING','COMPLETED')))");
            statement.execute("CREATE TABLE IF NOT EXISTS tasks ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,"
                + "title VARCHAR(120) NOT NULL, description VARCHAR(500) NOT NULL,"
                + "volunteer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE)");
            statement.execute("CREATE TABLE IF NOT EXISTS donations ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_type VARCHAR(8) NOT NULL CHECK (target_type IN ('PROJECT','EVENT')),"
                + "project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE, event_id BIGINT REFERENCES events(id) ON DELETE CASCADE,"
                + "donor_email VARCHAR(254) NOT NULL REFERENCES users(email), amount BIGINT NOT NULL CHECK (amount > 0), donation_date DATE NOT NULL,"
                + "CHECK ((target_type='PROJECT' AND project_id IS NOT NULL AND event_id IS NULL) OR"
                + " (target_type='EVENT' AND event_id IS NOT NULL AND project_id IS NULL)))");
            statement.execute("CREATE INDEX IF NOT EXISTS tasks_volunteer_idx ON tasks(volunteer_email)");
            statement.execute("CREATE INDEX IF NOT EXISTS donations_project_idx ON donations(project_id)");
            statement.execute("CREATE INDEX IF NOT EXISTS donations_event_idx ON donations(event_id)");
        } catch (SQLException e) {
            throw new IOException("Could not initialize the PostgreSQL database. Check PACT_DB_URL and credentials.", e);
        }

        if (hasData()) return;
        if (legacyFile != null && Files.exists(legacyFile)) {
            Properties legacy = new Properties();
            try (var input = Files.newInputStream(legacyFile)) { legacy.load(input); }
            if (legacy.containsKey("project.1.title")) {
                migrateLegacy(legacy);
                return;
            }
        }
        seedProjects();
    }

    private boolean hasData() throws IOException {
        return read(connection -> {
            try (Statement statement = connection.createStatement();
                 ResultSet result = statement.executeQuery("SELECT "
                     + "(SELECT COUNT(*) FROM users) + (SELECT COUNT(*) FROM projects) + (SELECT COUNT(*) FROM events)")) {
                result.next();
                return result.getLong(1) > 0;
            }
        });
    }

